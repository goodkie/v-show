'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(root,p),'utf8');
const html = read('extension/email-studio/index.html');
const js = read('extension/email-studio/email-template-studio.js');
const css = read('extension/email-studio/email-template-studio.css');
const popup = read('extension/popup.html');
const manifest=JSON.parse(read('extension/manifest.json'));
let checks=0;const check=(label,fn)=>{fn();checks++;console.log('PASS',label)};
check('studio opens from existing XPIDER top bar',()=>assert(popup.includes('href="email-studio/index.html"')));
check('studio loads bundled JavaScript',()=>assert(html.includes('src="email-template-studio.js"')));
check('studio loads bundled stylesheet',()=>assert(html.includes('href="email-template-studio.css"')));
check('studio has no inline JS blocks',()=>assert(!/<script(?![^>]*src=)[^>]*>[\s\S]*?<\/script>/i.test(html)));
check('studio has no inline style blocks',()=>assert(!/<style\b/i.test(html)));
check('studio has no remote scripts',()=>assert(!/<script[^>]*src="https?:/i.test(html)));
check('iframe sandbox still enabled',()=>assert(/<iframe[^>]+sandbox=""/.test(html)));
check('HTML/TXT/JSON local exports retained',()=>{for(const ext of ['html','txt','json'])assert(js.includes('xpider-vivpr-template.'+ext))});
check('marketing unsubscribe and content warnings retained',()=>{assert(js.includes('unsubscribe'));assert(js.includes('audit(v)'))});
check('no mail provider API or direct sending from UI',()=>assert(!/api\.resend\.com|sendOne\s*\(|fetch\s*\(|XMLHttpRequest/.test(js)));
check('extension action keeps original side panel',()=>assert.equal(manifest.side_panel.default_path,'popup.html'));
check('studio CSS exists and is nonempty',()=>assert(css.length>500));
console.log(checks+'/'+checks+' PASS');
